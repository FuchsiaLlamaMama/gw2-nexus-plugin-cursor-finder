#!/usr/bin/env python3
"""Emit preset_textures_data.h — the preset layer PNGs as C byte arrays.

The Pulse Ring, Corner Reticle and Beacon Crosshair are drawn in code
(src/entry.cpp: DrawPulseRing, DrawCornerReticle, DrawBeaconCrosshair), so they
have no layers here; Radar Dash and Soft Halo keep two layers each.

The DLL loads these via Textures_GetOrCreateFromMemory (no Windows resource
lookup, no module handle), which sidestepped a FindResource "resource not found"
failure with the .rc/RCDATA path. Regenerate after re-rasterizing the PNGs:

    python3 gen_texture_data.py    # run from the assets/ folder
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
PRESETS = HERE / "presets"
OUT = HERE / "preset_textures_data.h"

# (C symbol, filename) — order/names must match kPresetTex in entry.cpp.
LAYERS = [
    ("kRadarDashOutline",       "radar-dash-outline.png"),
    ("kRadarDashColour",        "radar-dash-colour.png"),
    ("kSoftHaloOutline",        "soft-halo-outline.png"),
    ("kSoftHaloColour",         "soft-halo-colour.png"),
]


def emit_array(sym: str, data: bytes) -> str:
    body = []
    for i in range(0, len(data), 20):
        body.append("    " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    return (f"inline const unsigned char {sym}[] = {{\n"
            + "\n".join(body)
            + f"\n}};\ninline const unsigned int {sym}_len = {len(data)}u;\n")


def main() -> None:
    parts = [
        "// GENERATED by gen_texture_data.py — do not edit by hand.",
        "// The image presets' outline/colour layer PNGs, embedded as byte arrays and",
        "// loaded via Textures_GetOrCreateFromMemory (see src/entry.cpp). The Pulse",
        "// Ring, Corner Reticle and Beacon Crosshair are drawn in code and have no",
        "// layers here.",
        "#pragma once",
        "",
        "namespace cursor_finder_art {",
        "",
    ]
    for sym, fname in LAYERS:
        data = (PRESETS / fname).read_bytes()
        parts.append(f"// {fname} ({len(data)} bytes)")
        parts.append(emit_array(sym, data))
    parts.append("} // namespace cursor_finder_art")
    OUT.write_text("\n".join(parts) + "\n")
    total = sum((PRESETS / f).stat().st_size for _, f in LAYERS)
    print(f"wrote {OUT.name}: {len(LAYERS)} arrays, {total} bytes of PNG")


if __name__ == "__main__":
    main()
